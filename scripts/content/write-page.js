// Writes years/<year>/page.html: the shared page in src/page.html with the year's SITE and PROJECTS
// data block, built from years/<year>/content/content.json (all text) and layout.json (images and
// framing). Run: npm run content   (NFH_YEAR=2026 npm run content for another year)
const fs = require("fs");
const Y = require("../year");
const PAGE = Y.PAGE;
const content = JSON.parse(fs.readFileSync(Y.file("content.json"), "utf8"));
const layout = JSON.parse(fs.readFileSync(Y.file("layout.json"), "utf8"));

const START = "/* ============================================================\n   SITE DATA";
const LEGACY_START = "/* ============================================================\n   EDIT HERE.";
const END = "/* ============================================================\n   Rendering.";

const js = v => JSON.stringify(v);
const c = content;
const W = c.welcome, A = c.about;

const SITE = {
  year: c.year,
  PER_PAGE: layout.perPage || 4,
  intro: c.cover.intro,
  footer: { email: c.cover.footerEmail, note: c.cover.footerNote },
  welcome: {
    heading: W.heading, lede: W.lede, invitation: W.invitation,
    whyHeading: A.heading, why: A.why, criteria: A.criteria, selection: A.selection, how: A.how, close: A.close
  }
};

const order = c.order.filter(s => c.projects[s]);
for (const s of Object.keys(c.projects)) if (!order.includes(s)) order.push(s);

const projectLines = order.map(slug => {
  const t = c.projects[slug];
  const l = (layout.projects || {})[slug] || {};
  const p = { slug, ...l, title: t.title, format: t.format, status: t.status, logline: t.logline, summary: t.summary,
    team: t.team || [], help: t.help || [], links: t.links || [], onRequest: t.onRequest || "", contact: t.contact || "",
    laurels: t.laurels || [], updates: t.updates || [] };
  return js(p);
});

const block = `${START}. Generated by scripts/content/write-page.js from
   years/${Y.Y}/content/content.json (text, mirrored from the Google Drive kit) and
   years/${Y.Y}/content/layout.json (images and framing). Do not edit by hand.
   Text uses **double asterisks** for the marker highlight.
   ============================================================ */
const SITE = ${JSON.stringify(SITE, null, 2)};

const PROJECTS = [
${projectLines.join(",\n")}
];

`;

let s = fs.readFileSync(Y.TEMPLATE, "utf8");
let a = s.indexOf(START);
if (a < 0) a = s.indexOf(LEGACY_START);
const b = s.indexOf(END);
if (a < 0 || b < 0 || b < a) throw new Error("data block markers not found in src/page.html");
// src/page.html is shared by every year: __YEAR__ marks the places outside the data block that name it.
const next = (s.slice(0, a) + block + s.slice(b)).replace(/__YEAR__/g, Y.Y);
const before = fs.existsSync(PAGE) ? fs.readFileSync(PAGE, "utf8") : "";
if (next !== before) { fs.writeFileSync(PAGE, next); console.log(`${Y.Y} page written: ${order.length} projects`); }
else console.log(`${Y.Y} page unchanged`);
